import crypto from 'node:crypto';
import { ForbiddenError, InvalidValueError } from '../../utils/errors.js';
import { Uuid } from '../../utils/uuid.js';
import type { GroupId } from '../challenge-group/challenge-group.js';
import type { MemberRole } from '../challenge-group/challenge-group.js';
import type { UserId } from '../user/user.js';

export class MessageId extends Uuid {
  declare private readonly brand: 'MessageId';

  static of(raw: unknown): MessageId {
    return new MessageId(Uuid.parse(raw, 'message id'));
  }

  static generate(): MessageId {
    return new MessageId(crypto.randomUUID());
  }
}

/** Generated by the client for each send, so a retried request is stored once. */
export class ClientMessageId extends Uuid {
  declare private readonly brand: 'ClientMessageId';

  static of(raw: unknown): ClientMessageId {
    return new ClientMessageId(Uuid.parse(raw, 'client message id'));
  }
}

export const MAX_MESSAGE_LENGTH = 2000;

export class InvalidMessageBodyError extends InvalidValueError {
  constructor() {
    super(`A message must be 1-${MAX_MESSAGE_LENGTH} characters`);
  }
}

export class MessageBody {
  private constructor(readonly value: string) {}

  static of(raw: unknown): MessageBody {
    const text = typeof raw === 'string' ? raw.trim() : '';
    if (text.length === 0 || text.length > MAX_MESSAGE_LENGTH) throw new InvalidMessageBodyError();
    return new MessageBody(text);
  }
}

export const MESSAGE_KINDS = ['text', 'system'] as const;
export type MessageKind = (typeof MESSAGE_KINDS)[number];

export function messageKindOf(raw: string): MessageKind {
  if (!MESSAGE_KINDS.some((kind) => kind === raw)) {
    throw new InvalidValueError(`Unknown message kind: ${raw}`);
  }
  return raw as MessageKind;
}

export interface ChatMessageState {
  id: MessageId;
  /** Assigned by the store on insert; null until the message is saved. */
  seq: number | null;
  groupId: GroupId;
  /** Null for system messages. */
  authorId: UserId | null;
  clientId: ClientMessageId | null;
  kind: MessageKind;
  body: MessageBody;
  createdAt: Date;
  deletedAt: Date | null;
}

// Entity: one message in a group's chat (ADR-0006). Text messages have an
// author; system messages are posted by the app for group events.
export class ChatMessage {
  readonly id: MessageId;
  readonly seq: number | null;
  readonly groupId: GroupId;
  readonly authorId: UserId | null;
  readonly clientId: ClientMessageId | null;
  readonly kind: MessageKind;
  readonly body: MessageBody;
  readonly createdAt: Date;
  private _deletedAt: Date | null;

  private constructor(state: ChatMessageState) {
    this.id = state.id;
    this.seq = state.seq;
    this.groupId = state.groupId;
    this.authorId = state.authorId;
    this.clientId = state.clientId;
    this.kind = state.kind;
    this.body = state.body;
    this.createdAt = state.createdAt;
    this._deletedAt = state.deletedAt;
  }

  static write(
    props: { groupId: GroupId; authorId: UserId; clientId: ClientMessageId; body: MessageBody },
    now: Date,
  ): ChatMessage {
    return new ChatMessage({
      ...props,
      id: MessageId.generate(),
      seq: null,
      kind: 'text',
      createdAt: now,
      deletedAt: null,
    });
  }

  static system(groupId: GroupId, body: MessageBody, now: Date): ChatMessage {
    return new ChatMessage({
      id: MessageId.generate(),
      seq: null,
      groupId,
      authorId: null,
      clientId: null,
      kind: 'system',
      body,
      createdAt: now,
      deletedAt: null,
    });
  }

  static reconstitute(state: ChatMessageState): ChatMessage {
    return new ChatMessage(state);
  }

  get deletedAt(): Date | null {
    return this._deletedAt;
  }

  get isDeleted(): boolean {
    return this._deletedAt !== null;
  }

  /**
   * Soft-deletes the message (F-GRP-02 rule 4): its author or the group admin may.
   * Returns false when it was already deleted, so a repeated delete is harmless.
   */
  deleteBy(userId: UserId, role: MemberRole, now: Date): boolean {
    if (this.kind === 'system') throw new ForbiddenError('System messages cannot be deleted');
    const isAuthor = this.authorId !== null && this.authorId.equals(userId);
    if (!isAuthor && role !== 'admin') {
      throw new ForbiddenError('Only the author or the group admin can delete this message');
    }
    if (this._deletedAt) return false;
    this._deletedAt = now;
    return true;
  }
}
